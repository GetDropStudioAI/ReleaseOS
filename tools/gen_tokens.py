#!/usr/bin/env python3
"""Writes the redesign tokens (D41, REOS-93) into docs/ui/tokens.css from docs/ui/redesign-tokens.json.

The JSON is the export of the Figma variables (colours, Light and Dark) plus the dimensions sampled from the frames. The generated block sits
between the BEGIN/END markers in tokens.css and is replaced on every run; nothing else in the file is touched. Light values apply by default;
Dark applies under the OS dark scheme unless the page says data-theme="light", and always under data-theme="dark". The theme selectors also
match any element, so a section can show the other theme (the component gallery shows both side by side).

    python3 tools/gen_tokens.py            # rewrite the block
    python3 tools/gen_tokens.py --check    # exit 1 if tokens.css is not what the JSON produces (CI and the web unit test use this)
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
JSON = ROOT / "docs/ui/redesign-tokens.json"
CSS = ROOT / "docs/ui/tokens.css"
BEGIN = "/* BEGIN redesign tokens: generated by tools/gen_tokens.py from docs/ui/redesign-tokens.json. Do not edit by hand. */"
END = "/* END redesign tokens */"


def block() -> str:
    data = json.loads(JSON.read_text(encoding="utf-8"))
    colours = data["variables"]
    dims = {k: v for k, v in data["dimensions"].items() if not k.startswith("_")}

    def decls(mode: str, indent: str = "    ") -> str:
        return "\n".join(f"{indent}{v['css']}: {v[mode].lower()};" for v in colours)

    light, dark = decls("light"), decls("dark")
    dimensions = "\n".join(f"    --{k}: {v};" for k, v in dims.items())
    return "\n".join([
        BEGIN,
        ":root, [data-theme=\"light\"] {",
        light,
        dimensions,
        "}",
        "@media (prefers-color-scheme: dark) {",
        "  :root:not([data-theme=\"light\"]) {",
        decls("dark", "      "),
        "  }",
        "}",
        "[data-theme=\"dark\"] {",
        dark,
        "}",
        "[data-theme=\"light\"] { color-scheme: light; }",
        "[data-theme=\"dark\"] { color-scheme: dark; }",
        END,
    ])


def render(css: str) -> str:
    new = block()
    if BEGIN in css:
        start, end = css.index(BEGIN), css.index(END) + len(END)
        return css[:start] + new + css[end:]
    return css.rstrip("\n") + "\n\n" + new + "\n"


def main() -> int:
    css = CSS.read_text(encoding="utf-8")
    out = render(css)
    if "--check" in sys.argv:
        if out != css:
            print("docs/ui/tokens.css is out of date: run python3 tools/gen_tokens.py", file=sys.stderr)
            return 1
        print("tokens.css matches redesign-tokens.json")
        return 0
    CSS.write_text(out, encoding="utf-8")
    print(f"wrote {sum(1 for _ in json.loads(JSON.read_text())['variables'])} colour tokens to {CSS.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
