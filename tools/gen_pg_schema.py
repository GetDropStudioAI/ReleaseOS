TYPE_MAP = {"INTEGER": "bigint", "REAL": "double precision", "TEXT": "text"}


def collect_idents(token_stmts):
    """Table names and column names (exact case) from every CREATE TABLE."""
    idents = set()
    for toks in token_stmts:
        sig = [t for t in toks if is_sig(t)]
        if len(sig) > 3 and sig[0] == ("word", "CREATE") and sig[1] == ("word", "TABLE"):
            idents.add(sig[2][1])
            lp = next(k for k, t in enumerate(toks) if t == ("punct", "("))
            rp = match_paren(toks, lp)
            for item in split_top(toks[lp + 1:rp]):
                s2 = [t for t in item if is_sig(t)]
                if s2 and s2[0][0] == "word" and s2[0][1] not in ("PRIMARY", "UNIQUE", "CHECK", "FOREIGN", "CONSTRAINT"):
                    idents.add(s2[0][1])
    return idents


FK_RE = re.compile(r"\s*REFERENCES\s+(\w+)\s*\(\s*(\w+)\s*\)((?:\s+ON\s+(?:DELETE|UPDATE)\s+(?:CASCADE|SET NULL|SET DEFAULT|RESTRICT|NO ACTION))*)", re.I)


def translate_table(toks, idents, todos, gen):
    sig = [t for t in toks if is_sig(t)]
    tname = sig[2][1]
    lp = next(k for k, t in enumerate(toks) if t == ("punct", "("))
    rp = match_paren(toks, lp)
    cols, fks, extra_check = [], [], 0
    for item in split_top(toks[lp + 1:rp]):
        text = untok(item).strip()
        if not text:
            continue
        where = f"table {tname}"
        head = text.split(None, 1)[0]
        if head in ("PRIMARY", "UNIQUE", "CHECK", "CONSTRAINT"):
            cols.append("    " + translate_sql(text, idents, where, todos))
            continue
        if head == "FOREIGN":
            m = re.match(r"FOREIGN\s+KEY\s*\(([^)]*)\)\s*(REFERENCES.*)$", text, re.S | re.I)
            f = FK_RE.match(" " + m.group(2)) if m else None
            if not f:
                todos.add(where, "table-level FOREIGN KEY the translator cannot parse", text[:80])
                continue
            fk_cols = ", ".join(quote_word(c.strip()) for c in m.group(1).split(","))
            fks.append(f'ALTER TABLE "{tname}" ADD FOREIGN KEY ({fk_cols}) REFERENCES "{f.group(1)}"("{f.group(2)}"){f.group(3)}')
            continue
        colname, rest = (text.split(None, 1) + [""])[:2]
        # lift REFERENCES out
        fm = FK_RE.search(rest)
        if fm:
            fks.append(f'ALTER TABLE "{tname}" ADD FOREIGN KEY ("{colname}") REFERENCES "{fm.group(1)}"("{fm.group(2)}"){fm.group(3)}')
            rest = rest[:fm.start()] + rest[fm.end():]
        nocase = re.search(r"\bCOLLATE\s+NOCASE\b", rest)
        if nocase:
            rest = re.sub(r"\s*\bCOLLATE\s+NOCASE\b", "", rest)
        if re.match(r"INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT", rest):
            rest = re.sub(r"^INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT", "bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", rest)
        else:
            tm = re.match(r"(\w+)", rest)
            tname_sql = tm.group(1) if tm else ""
            if tname_sql in TYPE_MAP:
                new = "citext" if (nocase and tname_sql == "TEXT") else TYPE_MAP[tname_sql]
                rest = new + rest[len(tname_sql):]
            else:
                todos.add(where, f"column type {tname_sql!r} not mapped", colname)
        rest = translate_sql(rest, idents, f"table {tname}.{colname}", todos)
        cols.append(f'    "{colname}" {rest}')
    sql = f'CREATE TABLE "{tname}" (\n' + ",\n".join(cols) + "\n)"
    return tname, sql, fks


def translate_index(toks, idents, todos):
    sig = [t for t in toks if is_sig(t)]
    unique = sig[1] == ("word", "UNIQUE")
    name = sig[3 if unique else 2][1]
    text = untok(toks).strip().rstrip(";")
    m = re.match(r"CREATE\s+(UNIQUE\s+)?INDEX\s+(\w+)\s+ON\s+(\w+)\s*", text, re.S)
    if not m:
        raise ValueError("unparsed index: " + text[:100])
    body = tokenize(text[m.end():])
    if not body or body[0] != ("punct", "("):
        raise ValueError("unparsed index column list: " + text[:100])
    close = match_paren(body, 0)
    cols_src = body[1:close]
    tail = untok(body[close + 1:]).strip()
    wm = re.match(r"WHERE\s+(.*)$", tail, re.S)
    if tail and not wm:
        raise ValueError("unparsed index tail: " + text[:100])
    cols = []
    for elem in split_top(cols_src):
        e = untok(elem).strip()
        e = re.sub(r"\s+COLLATE\s+NOCASE\b", "", e)
        if re.fullmatch(r"\w+(\s+(ASC|DESC))?", e):
            cols.append(translate_sql(e, idents, f"index {name}", todos))
        else:
            cols.append("(" + translate_sql(e, idents, f"index {name}", todos) + ")")
    where = translate_sql(wm.group(1), idents, f"index {name}", todos) if wm else None
    sql = f'CREATE {"UNIQUE " if m.group(1) else ""}INDEX "{m.group(2)}" ON "{m.group(3)}" ({", ".join(cols)})' + (f" WHERE {where}" if where else "")
    return name, sql


def translate_trigger(toks, idents, todos, file_order):
    text = untok(toks).strip()
    h = re.match(r"CREATE\s+TRIGGER\s+(\w+)\s+(BEFORE|AFTER)\s+(INSERT|DELETE|UPDATE(?:\s+OF\s+[\w,\s]+?)?)\s+ON\s+(\w+)\s*(?:FOR\s+EACH\s+ROW\s*)?", text, re.S)
    if not h:
        raise ValueError("unparsed trigger header: " + text[:100])
    name, timing, event, table = h.group(1), h.group(2), " ".join(h.group(3).split()), h.group(4)
    rest = text[h.end():]
    rest_toks = tokenize(rest)
    # WHEN <cond> BEGIN <body> END ;
    sig_idx = [k for k, t in enumerate(rest_toks) if is_sig(t)]
    first = rest_toks[sig_idx[0]]
    when = None
    depth = 0
    bi = None
    for k in sig_idx:
        t = rest_toks[k]
        if t == ("punct", "("):
            depth += 1
        elif t == ("punct", ")"):
            depth -= 1
        elif t == ("word", "BEGIN") and depth == 0:
            bi = k
            break
    if bi is None:
        raise ValueError("trigger without BEGIN: " + name)
    if first == ("word", "WHEN"):
        when = untok(rest_toks[sig_idx[0] + 1:bi]).strip()
    # body tokens: between BEGIN and the final END ;
    end_i = max(k for k in sig_idx if rest_toks[k] == ("word", "END"))
    body_toks = rest_toks[bi + 1:end_i]
    where = f"trigger {name}"
    ev = event.split()[0]
    upd_of = None
    if event.startswith("UPDATE OF"):
        upd_of = [c.strip() for c in event[len("UPDATE OF"):].split(",")]
    pg_name = f"t{1000 - file_order:03d}_{name}"
    if file_order >= 1000:
        todos.add(where, "more than 999 triggers: the t{1000-n} numbering runs out")
    if len(pg_name) > 63:
        todos.add(where, "trigger name over 63 bytes", pg_name)
    lines, messages = [], []
    if when:
        w = translate_sql(when, idents, where, todos)
        ret = "OLD" if ev == "DELETE" else "NEW"
        lines.append(f"    IF NOT COALESCE(({w}), false) THEN RETURN {ret}; END IF;")
    for st in split_top(body_toks, ";"):
        stxt = untok(st).strip()
        if not stxt:
            continue
        m = re.match(r"SELECT\s+RAISE\s*\(\s*ABORT\s*,\s*('(?:[^']|'')*')\s*\)\s*(?:WHERE\s+(.*))?$", stxt, re.S | re.I)
        if m:
            msg = m.group(1)
            messages.append(msg[1:-1].replace("''", "'"))
            cond = translate_sql(m.group(2), idents, where, todos) if m.group(2) else "true"
            lines.append(f"    IF ({cond}) THEN\n        RAISE EXCEPTION USING ERRCODE = '{RAISE_SQLSTATE}', MESSAGE = {msg}, DETAIL = TG_NAME;\n    END IF;")
        elif re.match(r"SELECT\s+RAISE", stxt, re.I):
            lines.append("    " + todos.add(where, "RAISE form other than RAISE(ABORT, 'msg')", stxt[:60]))
        else:
            lines.append("    " + translate_sql(stxt, idents, where, todos) + ";")
    ret = "OLD" if (timing == "BEFORE" and ev == "DELETE") else ("NEW" if timing == "BEFORE" else "NULL")
    fn = (f'CREATE OR REPLACE FUNCTION "{pg_name}"() RETURNS trigger LANGUAGE plpgsql AS $fn$\nBEGIN\n'
          + "\n".join(lines) + f"\n    RETURN {ret};\nEND\n$fn$")
    ev_sql = ev if not upd_of else "UPDATE OF " + ", ".join(quote_word(c) for c in upd_of)
    trg = f'CREATE TRIGGER "{pg_name}" {timing} {ev_sql} ON "{table}" FOR EACH ROW EXECUTE FUNCTION "{pg_name}"()'
    info = {"name": name, "pg_name": pg_name, "table": table, "timing": timing, "event": ev, "update_of": upd_of,
            "file_order": file_order, "messages": messages, "when": when}
    return info, fn, trg


def generate(schema_text=None):
    text = schema_text if schema_text is not None else open(SCHEMA, encoding="utf-8").read()
    tokens = tokenize(text)
    stmts = list(split_statements(tokens))
    gen = Generated()
    todos = gen.todos
    idents = collect_idents(stmts)
    src = {"tables": len(re.findall(r"(?m)^CREATE TABLE\b", text)),
           "indexes": len(re.findall(r"(?m)^CREATE (?:UNIQUE )?INDEX\b", text)),
           "triggers": len(re.findall(r"(?m)^CREATE TRIGGER\b", text))}
    gen.source_counts = src
    for kind, name, sql in PREAMBLE:
        gen.statements.append(Stmt(kind, name, sql))
    tables, fks, rest = [], [], []
    trig_order = 0
    for toks in stmts:
        sig = [t for t in toks if is_sig(t)]
        if not sig:
            continue
        head = (sig[0][1], sig[1][1] if len(sig) > 1 else "")
        if head == ("CREATE", "TABLE"):
            name, sql, f = translate_table(toks, idents, todos, gen)
            tables.append(Stmt("table", name, sql))
            fks.extend(Stmt("foreign-key", name, x) for x in f)
        elif head == ("CREATE", "INDEX") or head == ("CREATE", "UNIQUE"):
            name, sql = translate_index(toks, idents, todos)
            rest.append(Stmt("index", name, sql))
        elif head == ("CREATE", "TRIGGER"):
            trig_order += 1
            info, fn, trg = translate_trigger(toks, idents, todos, trig_order)
            gen.triggers.append(info)
            rest.append(Stmt("trigger-function", info["pg_name"], fn))
            rest.append(Stmt("trigger", info["pg_name"], trg))
        elif head[0] in ("INSERT", "UPDATE", "DELETE"):
            rest.append(Stmt("data", head[0] + " " + sig[2][1], translate_sql(untok(toks).strip().rstrip(";"), idents, "seed data", todos)))
        else:
            raise ValueError("statement the generator does not know: " + untok(toks).strip()[:100])
    gen.statements += tables + fks + rest
    gen.counts = {"tables": len(tables), "foreign keys": len(fks),
                  "indexes": sum(1 for s in rest if s.kind == "index"), "triggers": len(gen.triggers)}
    gen.idents = idents
    return gen


def check(gen):
    """Fail only when the Postgres schema cannot be PRODUCED: a source statement was dropped or not parsed."""
    problems = []
    for key in ("tables", "indexes", "triggers"):
        if gen.counts[key] != gen.source_counts[key]:
            problems.append(f"{key}: db/schema.sql has {gen.source_counts[key]}, the generator produced {gen.counts[key]}")
    if gen.counts["tables"] == 0:
        problems.append("no tables generated")
    names = [t["pg_name"] for t in gen.triggers]
    if len(set(names)) != len(names):
        problems.append("duplicate trigger names")
    return problems


def report(gen):
    out = [f"source: {gen.source_counts}", f"generated: {gen.counts}", f"TODO markers: {len(gen.todos.items)}"]
    for where, construct, detail in gen.todos.items:
        out.append(f"  {where}: {construct} {detail}".rstrip())
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out")
    ap.add_argument("--report", action="store_true")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    try:
        gen = generate()
    except Exception as e:                                # a parse failure IS the drift signal
        print(f"gen_pg_schema: cannot produce the Postgres schema from db/schema.sql: {e}", file=sys.stderr)
        return 1
    if a.check:
        problems = check(gen)
        print(report(gen))
        for p in problems:
            print("FAIL " + p, file=sys.stderr)
        return 1 if problems else 0
    if a.report:
        print(report(gen))
        return 0
    sql = gen.sql()
    if a.out:
        open(a.out, "w", encoding="utf-8").write(sql)
    else:
        print(sql)
    return 0


if __name__ == "__main__":
    sys.exit(main())
