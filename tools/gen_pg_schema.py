#!/usr/bin/env python3
"""Generate a PostgreSQL schema from db/schema.sql at run time (REOS-195, plan: docs/proposals/postgres-port-plan.md sections 2-4).

The Postgres schema is never committed: it is derived from db/schema.sql every time, so it cannot drift while other
stories add tables. This is a FIRST-PASS translator for the oracle (tests/reference/test_schema.py --dialect postgres),
not the production migration. Where a construct cannot be translated yet it emits a `TODO(pg)` marker in the SQL and
records it in the report.

Strategy (plan section 2 and 3):
  * identifiers keep their PascalCase and are quoted ("StageGates"); a word is quoted when it exactly matches a table or
    column name of the schema, so keywords and aliases are left alone;
  * INTEGER -> bigint, REAL -> double precision, TEXT -> text, COLLATE NOCASE -> citext,
    INTEGER PRIMARY KEY AUTOINCREMENT -> bigint GENERATED BY DEFAULT AS IDENTITY;
  * REFERENCES clauses are lifted out of CREATE TABLE into ALTER TABLE ... ADD FOREIGN KEY after all tables exist
    (SQLite allows forward references, Postgres does not);
  * every trigger becomes one PL/pgSQL function + one row trigger named t{1000-file_order}_{name}, so Postgres's
    name-order firing equals SQLite's newest-first firing (plan 3.2, option A); WHEN moves into the body;
    SELECT RAISE(ABORT, msg) WHERE cond becomes IF cond THEN RAISE EXCEPTION (SQLSTATE RE001, DETAIL = trigger name);
  * GLOB -> app_glob(), strftime(..,'now') -> app_now(), json_valid/json_type/date -> app_* helpers,
    json_object -> json_build_object, json_group_array -> app_json_group_array,
    IS [NOT] <non-null> -> IS [NOT] DISTINCT FROM, lower(hex(randomblob(16))) -> replace(gen_random_uuid()::text,'-','').

Usage:
  python3 tools/gen_pg_schema.py                 # print the generated SQL
  python3 tools/gen_pg_schema.py --out FILE      # write it
  python3 tools/gen_pg_schema.py --report        # print the TODO list and statement counts
  python3 tools/gen_pg_schema.py --check         # exit 1 only if the schema CANNOT be produced (parse failure, count mismatch)
Library use: generate(schema_text) -> Generated; translate_sql(sql, idents) for the oracle's per-case SQL.
"""
import argparse, os, re, sys

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SCHEMA = os.path.join(ROOT, "db", "schema.sql")
RAISE_SQLSTATE = "RE001"          # one custom SQLSTATE for every trigger RAISE (plan 4.7), mapped to 422 DbRule by the app

# ----------------------------------------------------------------------------------------------------------------- tokens
TOKEN = re.compile(r"""
    (?P<comment>--[^\n]*)
  | (?P<str>'(?:[^']|'')*')
  | (?P<word>[A-Za-z_][A-Za-z0-9_]*)
  | (?P<num>\d+(?:\.\d+)?)
  | (?P<ws>\s+)
  | (?P<punct>.)
""", re.X | re.S)


def tokenize(sql, keep_comments=False):
    out = []
    for m in TOKEN.finditer(sql):
        kind = m.lastgroup
        if kind == "comment" and not keep_comments:
            continue
        out.append((kind, m.group()))
    return out


def untok(tokens):
    return "".join(t for _, t in tokens)


def is_sig(tok):
    return tok[0] not in ("ws", "comment")


def next_sig(tokens, i):
    i += 1
    while i < len(tokens) and not is_sig(tokens[i]):
        i += 1
    return i


def prev_sig(tokens, i):
    i -= 1
    while i >= 0 and not is_sig(tokens[i]):
        i -= 1
    return i


def match_paren(tokens, i):
    """tokens[i] is '(' ; return the index of its matching ')'."""
    depth = 0
    for j in range(i, len(tokens)):
        if tokens[j] == ("punct", "("):
            depth += 1
        elif tokens[j] == ("punct", ")"):
            depth -= 1
            if depth == 0:
                return j
    raise ValueError("unbalanced parenthesis")


def split_top(tokens, sep=","):
    """Split a token list on a top-level punctuation separator."""
    parts, cur, depth = [], [], 0
    for t in tokens:
        if t == ("punct", "("):
            depth += 1
        elif t == ("punct", ")"):
            depth -= 1
        if t == ("punct", sep) and depth == 0:
            parts.append(cur)
            cur = []
        else:
            cur.append(t)
    parts.append(cur)
    return parts


class Todos:
    def __init__(self):
        self.items = []          # (where, construct, detail)

    def add(self, where, construct, detail=""):
        self.items.append((where, construct, detail))
        return f"/* TODO(pg): {construct} */"


# ---------------------------------------------------------------------------------------------------- expression rewriting
def quote_word(w):
    return '"' + w + '"'


UNSUPPORTED_FUNCS = {"strftime", "datetime", "julianday", "unixepoch", "printf", "typeof", "instr", "ifnull", "iif",
                     "json_extract", "json_each", "group_concat", "randomblob", "hex", "total_changes", "last_insert_rowid"}


def _operand_left(tokens, i):
    """Start index of the operand that ends just before token i."""
    j = prev_sig(tokens, i)
    if j < 0:
        return None
    if tokens[j] == ("punct", ")"):
        depth = 0
        for k in range(j, -1, -1):
            if tokens[k] == ("punct", ")"):
                depth += 1
            elif tokens[k] == ("punct", "("):
                depth -= 1
                if depth == 0:
                    p = prev_sig(tokens, k)
                    return p if p >= 0 and tokens[p][0] == "word" and p == k - 1 else k
        return None
    if tokens[j][0] in ("word", "str", "num"):
        while True:                       # a.b.c
            d = prev_sig(tokens, j)
            if d >= 0 and tokens[d] == ("punct", ".") and d == j - 1:
                w = prev_sig(tokens, d)
                if w >= 0 and tokens[w][0] == "word":
                    j = w
                    continue
            break
        return j
    return None


def _operand_right(tokens, i):
    """End index (inclusive) of the operand that starts after token i."""
    j = next_sig(tokens, i)
    if j >= len(tokens):
        return None
    if tokens[j][0] == "str" or tokens[j][0] == "num":
        return j
    if tokens[j][0] == "word":
        while True:
            d = j + 1
            if d + 1 < len(tokens) and tokens[d] == ("punct", ".") and tokens[d + 1][0] == "word":
                j = d + 1
                continue
            break
        if j + 1 < len(tokens) and tokens[j + 1] == ("punct", "("):
            return match_paren(tokens, j + 1)
        return j
    if tokens[j] == ("punct", "("):
        return match_paren(tokens, j)
    return None


def rewrite_glob(tokens, where, todos):
    while True:
        gi = next((k for k, t in enumerate(tokens) if t == ("word", "GLOB")), None)
        if gi is None:
            return tokens
        left = _operand_left(tokens, gi)
        right = _operand_right(tokens, gi)
        if left is None or right is None:
            todos.add(where, "GLOB with an operand the translator cannot find")
            tokens[gi] = ("word", "GLOB /* TODO(pg) */")
            continue
        neg = False
        ls = left
        p = prev_sig(tokens, gi)
        # `X NOT GLOB p`: the NOT sits between the operand and GLOB
        if p >= 0 and tokens[p] == ("word", "NOT"):
            neg = True
            left = _operand_left(tokens, p)
            ls = left
        l_txt = untok(tokens[ls:(p if neg else gi)]).strip()
        r_txt = untok(tokens[gi + 1:right + 1]).strip()
        repl = tokenize(("NOT " if neg else "") + f"app_glob({l_txt}, {r_txt})")
        tokens = tokens[:ls] + repl + tokens[right + 1:]


def rewrite_is(tokens):
    """`a IS NOT b` -> `a IS DISTINCT FROM b`, `a IS b` -> `a IS NOT DISTINCT FROM b` unless b is NULL / TRUE / FALSE."""
    out, i = [], 0
    while i < len(tokens):
        t = tokens[i]
        if t == ("word", "IS"):
            j = next_sig(tokens, i)
            negated = j < len(tokens) and tokens[j] == ("word", "NOT")
            k = next_sig(tokens, j) if negated else j
            nxt = tokens[k] if k < len(tokens) else ("punct", "")
            if nxt[0] == "word" and nxt[1] in ("NULL", "TRUE", "FALSE", "DISTINCT", "UNKNOWN"):
                out.append(t)
                i += 1
                continue
            out.append(("word", "IS DISTINCT FROM" if negated else "IS NOT DISTINCT FROM"))
            i = k if k > i else i + 1
            # keep whitespace separation before the right operand
            out.append(("ws", " "))
            continue
        out.append(t)
        i += 1
    return out


def rewrite_calls(tokens, where, todos, idents):
    """Function renames that need the argument list: json_group_array, json_object, json_valid, json_type, date."""
    out, i = [], 0
    renames = {"json_valid": "app_json_valid", "json_type": "app_json_type", "date": "app_date",
               "json_object": "json_build_object"}
    while i < len(tokens):
        t = tokens[i]
        if t[0] == "word" and i + 1 < len(tokens) and tokens[i + 1] == ("punct", "("):
            close = match_paren(tokens, i + 1)
            inner = rewrite_calls(tokens[i + 2:close], where, todos, idents)
            name = t[1]
            if name == "json_group_array":
                out.append(("word", "app_json_group_array("))
                out.extend(inner)
                out.append(("punct", ")"))
            elif name in renames and name not in idents:
                out.append(("word", renames[name] + "("))
                out.extend(inner)
                out.append(("punct", ")"))
            elif name.lower() in UNSUPPORTED_FUNCS:
                out.append(("word", name + todos.add(where, f"SQLite function {name}()")))
                out.append(("punct", "("))
                out.extend(inner)
                out.append(("punct", ")"))
            else:
                out.append(t)
                out.append(("punct", "("))
                out.extend(inner)
                out.append(("punct", ")"))
            i = close + 1
            continue
        out.append(t)
        i += 1
    return out


def translate_sql(sql, idents, where="", todos=None):
    """Translate one SQLite expression or statement to Postgres. `idents` = set of exact-case table and column names."""
    todos = todos if todos is not None else Todos()
    s = re.sub(r"strftime\(\s*'%Y-%m-%dT%H:%M:%SZ'\s*,\s*'now'\s*\)", "app_now()", sql)
    s = re.sub(r"lower\(\s*hex\(\s*randomblob\(\s*16\s*\)\s*\)\s*\)", "replace(gen_random_uuid()::text,'-','')", s)
    s = re.sub(r"printf\(\s*'%0(\d+)d'\s*,\s*([^()]+?)\s*\)", r"lpad((\2)::text,\1,'0')", s)   # oracle fixtures only
    tokens = tokenize(s)
    tokens = rewrite_calls(tokens, where, todos, idents)
    tokens = rewrite_glob(tokens, where, todos)
    tokens = rewrite_is(tokens)
    out = []
    for kind, text in tokens:
        if kind == "word" and text in idents:
            out.append(quote_word(text))
        else:
            out.append(text)
    return "".join(out)


# ------------------------------------------------------------------------------------------------------------ statements
def split_statements(tokens):
    """Yield token lists, one per top-level statement. CREATE TRIGGER ends at END; (CASE .. END is counted)."""
    stmt, depth, case_depth, trigger = [], 0, 0, False
    for t in tokens:
        stmt.append(t)
        if t[0] == "word":
            if t[1] == "TRIGGER" and [x for x in stmt if is_sig(x)][:2] == [("word", "CREATE"), ("word", "TRIGGER")]:
                trigger = True
            if trigger and t[1] == "CASE":
                case_depth += 1
            if trigger and t[1] == "END":
                if case_depth > 0:
                    case_depth -= 1
        elif t == ("punct", "("):
            depth += 1
        elif t == ("punct", ")"):
            depth -= 1
        elif t == ("punct", ";") and depth == 0:
            if trigger:
                sig = [x for x in stmt if is_sig(x)]
                if len(sig) >= 2 and sig[-2] == ("word", "END") and case_depth == 0:
                    yield stmt
                    stmt, trigger = [], False
            else:
                yield stmt
                stmt = []
    if any(is_sig(x) for x in stmt):
        raise ValueError("unterminated statement at end of file: " + untok(stmt)[:80])


class Stmt:
    def __init__(self, kind, name, sql):
        self.kind, self.name, self.sql = kind, name, sql


class Generated:
    def __init__(self):
        self.statements = []     # in execution order
        self.todos = Todos()
        self.counts = {}
        self.source_counts = {}
        self.triggers = []       # dicts: name, pg_name, table, timing, event, file_order, messages

    def sql(self):
        parts = []
        for s in self.statements:
            parts.append(f"-- {s.kind}: {s.name}\n{s.sql};\n")
        return "\n".join(parts)


